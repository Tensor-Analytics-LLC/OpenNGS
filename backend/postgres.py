"""Bounded PostgreSQL pool behind the existing small DB interface.

SQLite remains the desktop format and the per-artifact read index. Application
state on AWS uses PostgreSQL. The global write lock preserves the audit chain
and quota reservations across processes; expensive work stays outside it.
"""
import re
import threading
import time
from contextlib import contextmanager

_pool = None
_lock = threading.Lock()

class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

def rows(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))

def pool():
    global _pool
    from .config import DATABASE_URL
    if _pool is None:
        with _lock:
            if _pool is None:
                from psycopg_pool import ConnectionPool
                _pool = ConnectionPool(DATABASE_URL, min_size=2, max_size=8, timeout=2,
                    max_waiting=12, kwargs={'autocommit': True, 'row_factory': rows,
                    'connect_timeout': 8, 'options': '-c statement_timeout=5000 -c lock_timeout=1000'})
    return _pool

def sql(statement):
    if statement.lstrip().upper().startswith('CREATE TABLE'):
        statement=re.sub(r'\bINTEGER\b','BIGINT',statement)
        statement=re.sub(r'\bREAL\b','DOUBLE PRECISION',statement)
    statement = statement.replace('%', '%%').replace('?', '%s')
    statement = statement.replace("json_extract(metadata,'$.uploaded')=1", "(metadata::jsonb->>'uploaded')='true'")
    statement = statement.replace('MAX(0,', 'GREATEST(0,')
    statement = statement.replace('json_patch(assets.metadata,excluded.metadata)', '(assets.metadata::jsonb || excluded.metadata::jsonb)::text')
    return statement

def close():
    if _pool is not None:_pool.close()

class Connection:
    def __init__(self):
        self.raw = pool().getconn()
        self.transaction = False
    def execute(self, statement, args=()):
        if statement == 'BEGIN IMMEDIATE':
            # Retry only admission to the write transaction. No application
            # statement or external operation has run yet. A blocking advisory
            # lock inherited the one-second row-lock timeout and could fail an
            # accepted scientific stage during normal migration commits.
            deadline=time.monotonic()+8
            while True:
                self.raw.execute('BEGIN')
                self.transaction=True
                try:
                    acquired=self.raw.execute('SELECT pg_try_advisory_xact_lock(684731923)').fetchone()[0]
                except BaseException:
                    self.rollback()
                    raise
                if acquired:
                    return self.raw.cursor()
                self.rollback()
                if time.monotonic()>=deadline:
                    raise TimeoutError('Database writer admission remained busy for eight seconds; no transaction body was executed')
                time.sleep(.05)
        return self.raw.execute(sql(statement), args)
    def executescript(self, script):
        script = script.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        script = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', script)
        script = re.sub(r'\bINTEGER\b', 'BIGINT', script)
        for statement in script.split(';'):
            if statement.strip(): self.raw.execute(statement)
    def commit(self):
        self.raw.execute('COMMIT'); self.transaction = False
    def rollback(self):
        self.raw.execute('ROLLBACK'); self.transaction = False
    def close(self):
        if self.transaction: self.rollback()
        pool().putconn(self.raw)
